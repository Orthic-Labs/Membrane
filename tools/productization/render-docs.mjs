// MBR-1001 — Deterministic renderers for the generated product docs and the
// README link inventory.
//
// docs/product.md, docs/architecture.md, docs/operations.md, and docs/protocol.md
// are DERIVED artifacts: every claim in them (tool count, adapter list, platform
// status) is rendered from the same product truth that
// tools/productization/generate-product-truth.mjs computes from live source
// (mcp/server.mjs + docs/membrane/capability-matrix.v1.json). Hand-edits are
// overwritten by regeneration; `node tools/productization/check-docs.mjs --check`
// fails when any of these files is stale or a README link is broken.

/** Word forms the generated docs use for counts. */
const COUNT_WORDS = ["zero", "one", "two", "three", "four", "five", "six", "seven", "eight", "nine", "ten", "eleven", "twelve"];

export function countWord(n) {
  return COUNT_WORDS[n] ?? String(n);
}

/** Split capability-matrix support tiers into tier-1 and best-effort platforms. */
export function platformStatus(matrix) {
  const tiers = matrix.support_tiers || {};
  return {
    tier1: tiers.tier_1 || [],
    bestEffort: tiers.tier_2_best_effort || [],
  };
}

const GENERATED_BY =
  "This file is generated by `tools/productization/generate-product-truth.mjs`.\n" +
  "Do not hand-edit; regenerate instead. `node tools/productization/check-docs.mjs --check`\n" +
  "fails if this file is stale.";

function toolTable(truth) {
  return truth.tools.map((name) => `| \`${name}\` |`).join("\n");
}

function adapterLines(truth) {
  return truth.adapters.map((name) => `- \`${name}\``).join("\n");
}


function derivedFromLines(truth) {
  return truth.generatedFrom.map((source) => `- \`${source}\``);
}

/** docs/product.md — what the product is and does, grounded in source truth. */
export function renderProductDoc(truth, platforms) {
  return [
    "# Membrane — product overview (generated)",
    "",
    GENERATED_BY,
    "",
    "Membrane sits between an agent and its sources and returns the smallest useful",
    "set of current code, rules, decisions, and memory for each task — plus a receipt",
    "showing what entered context, what did not, and why. See `README.md` for the",
    "narrative overview; this file carries the source-derived facts.",
    "",
    "## Public surface",
    "",
    `- **MCP server** — ${countWord(truth.toolCount)} tools over stdio:`,
    "",
    toolTable(truth),
    "",
    `- **Client adapters** — ${countWord(truth.adapterCount)} host adapters from the vendored capability matrix:`,
    "",
    adapterLines(truth),
    "",
    "## Platform status",
    "",
    platformSentence(platforms),
    "",
    "## Derived from",
    "",
    ...derivedFromLines(truth),
    "",
  ].join("\n");
}


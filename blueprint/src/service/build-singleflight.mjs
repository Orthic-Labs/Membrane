import { execFileSync, spawn } from "node:child_process";
import { createHash } from "node:crypto";
import { existsSync, lstatSync, readFileSync, readlinkSync, realpathSync } from "node:fs";
import { join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const BUILD_SCRIPT = fileURLToPath(new URL("../../scripts/blueprint.mjs", import.meta.url));
const BUILD_INPUT_SIDECARS = Object.freeze(["config.json", "understanding.json", "verdicts.json", "reconcile.json"]);
const EXCLUDED_SEGMENTS = new Set([".git", "node_modules", "target"]);

function typedError(code, message) {
  return Object.assign(new Error(message), { code });
}

function canonicalRoot(root) {
  if (typeof root !== "string" || !root.trim()) throw typedError("build_root_required", "build root is required");
  const absolute = resolve(String(root));
  return existsSync(absolute) ? realpathSync.native(absolute) : absolute;
}

function normalizedOutDir(value = ".agent") {
  return String(value).replaceAll("\\", "/").replace(/^\.\//, "");
}

function normalizedOptions(input = {}) {
  return Object.freeze({
    limit: Math.max(0, Number(input.limit ?? 0) || 0),
    check: Boolean(input.check),
    noReadmeLink: Boolean(input.noReadmeLink ?? input["no-readme-link"]),
  });
}

function repositoryFiles(root) {
  try {
    return execFileSync("git", ["ls-files", "--cached", "--others", "--exclude-standard", "-z"], {
      cwd: root,
      encoding: "utf8",
      maxBuffer: 512 * 1024 * 1024,
      stdio: ["ignore", "pipe", "ignore"],
      windowsHide: true,
    }).split("\0").filter(Boolean).sort();
  } catch (error) {
    throw typedError("build_fingerprint_failed", `build input inventory failed: ${error.message}`);
  }
}

function hashPath(hash, root, path) {
  const absolute = join(root, path);
  if (!existsSync(absolute)) return;
  const before = lstatSync(absolute, { bigint: true });
  hash.update(path); hash.update("\0");
  if (before.isSymbolicLink()) {
    hash.update("symlink\0"); hash.update(readlinkSync(absolute));
  } else if (before.isFile()) {
    hash.update("file\0");
    let content = readFileSync(absolute);
    if (path.endsWith(".md")) {
      let text = content.toString("utf8").replace(/\r\n?/g, "\n");
      if (text.startsWith("<!-- generated by blueprint")) text = "<!-- generated by blueprint -->";
      if (path === "README.md") text = text.replace(/\n?<!-- blueprint:docs:start -->[\s\S]*?<!-- blueprint:docs:end -->\n?/, "");
      content = Buffer.from(text);
    }
    hash.update(content);
  } else {
    hash.update("other\0");
  }
  const after = lstatSync(absolute, { bigint: true });
  if (before.dev !== after.dev || before.ino !== after.ino || before.size !== after.size || before.mtimeNs !== after.mtimeNs) {
    throw typedError("build_inputs_unstable", `build input changed while fingerprinting: ${path}`);
  }
  hash.update("\0");
}

export function buildFingerprint({ root: inputRoot, outDir: inputOutDir = ".agent", options: inputOptions = {} }) {
  const root = canonicalRoot(inputRoot);
  const outDir = normalizedOutDir(inputOutDir);
  const options = normalizedOptions(inputOptions);
  const hash = createHash("sha256");
  hash.update(JSON.stringify({ root, outDir, options })); hash.update("\0");
  const relativeOut = relative(root, join(root, outDir)).replaceAll("\\", "/");
  const outputPrefix = relativeOut && relativeOut !== "." && relativeOut !== ".." && !relativeOut.startsWith("../") ? `${relativeOut.replace(/\/$/, "")}/` : null;
  for (const path of repositoryFiles(root)) {
    const normalized = path.replaceAll("\\", "/");
    if (normalized.split("/").some((segment) => EXCLUDED_SEGMENTS.has(segment))) continue;
    if (outputPrefix && (normalized === relativeOut || normalized.startsWith(outputPrefix))) continue;
    hashPath(hash, root, normalized);
  }
  for (const name of BUILD_INPUT_SIDECARS) hashPath(hash, root, join(outDir, name).replaceAll("\\", "/"));
  return Object.freeze({ root, outDir, options, fingerprint: hash.digest("hex") });
}

export function runLocalBuild({ root, outDir, options }) {
  const args = [BUILD_SCRIPT, "build", "--root", root, "--out", outDir];
  if (options.limit > 0) args.push("--limit", String(options.limit));
  if (options.check) args.push("--check");
  if (options.noReadmeLink) args.push("--no-readme-link");
  return new Promise((resolveBuild, rejectBuild) => {
    const child = spawn(process.execPath, args, {
      cwd: root,
      env: { ...process.env, BLUEPRINT_LOCAL_BUILD: "1" },
      stdio: ["ignore", "pipe", "pipe"],
      windowsHide: true,
    });
    const stdout = [];
    const stderr = [];
    child.stdout.on("data", (chunk) => stdout.push(chunk));
    child.stderr.on("data", (chunk) => stderr.push(chunk));
    child.once("error", (error) => rejectBuild(typedError("build_spawn_failed", String(error.message ?? error))));
    child.once("close", (exitCode, signal) => resolveBuild({
      schemaVersion: 1,
      kind: "build",
      exitCode: Number.isInteger(exitCode) ? exitCode : 10,
      signal: signal ?? null,
      stdout: Buffer.concat(stdout).toString("utf8"),
      stderr: Buffer.concat(stderr).toString("utf8"),
    }));
  });
}

export function createBuildSingleflight({ fingerprint = buildFingerprint, runner = runLocalBuild } = {}) {
  const roots = new Map();
  const idleWaiters = new Set();

  function notifyIdle() {
    if ([...roots.values()].some((state) => state.running || state.queue.length > 0)) return;
    for (const resolveIdle of idleWaiters) resolveIdle();
    idleWaiters.clear();
  }

  function startNext(state) {
    if (state.running || state.queue.length === 0) return;
    const entry = state.queue.shift();
    state.running = entry;
    entry.work = Promise.resolve().then(() => runner(entry.identity));
    entry.work.then(
      (result) => settleEntry(entry, null, { ...result, repoRoot: entry.identity.root, outDir: entry.identity.outDir, fingerprint: entry.identity.fingerprint }),
      (error) => settleEntry(entry, error),
    ).finally(() => {
      state.running = null;
      if (state.queue.length === 0) roots.delete(entry.identity.root);
      startNext(state);
      notifyIdle();
    });
  }

  function settleEntry(entry, error, result = null) {
    entry.settled = true;
    for (const waiter of entry.waiters) {
      if (!waiter.active) continue;
      waiter.active = false;
      waiter.signal?.removeEventListener("abort", waiter.onAbort);
      if (error) waiter.reject(error); else waiter.resolve(result);
    }
    entry.waiters.clear();
  }

  function attach(entry, signal) {
    return new Promise((resolveWaiter, rejectWaiter) => {
      if (signal?.aborted) return rejectWaiter(typedError("request_cancelled", "request cancelled"));
      const waiter = { active: true, signal, resolve: resolveWaiter, reject: rejectWaiter, onAbort: null };
      waiter.onAbort = () => {
        if (!waiter.active) return;
        waiter.active = false;
        entry.waiters.delete(waiter);
        rejectWaiter(typedError("request_cancelled", "request cancelled"));
        if (!entry.work && entry.waiters.size === 0) {
          const index = entry.state.queue.indexOf(entry);
          if (index >= 0) entry.state.queue.splice(index, 1);
          if (!entry.state.running && entry.state.queue.length === 0) roots.delete(entry.identity.root);
          notifyIdle();
        }
      };
      entry.waiters.add(waiter);
      signal?.addEventListener("abort", waiter.onAbort, { once: true });
      if (signal?.aborted) waiter.onAbort();
    });
  }

  return Object.freeze({
    build(input = {}, { signal } = {}) {
      if (signal?.aborted) return Promise.reject(typedError("request_cancelled", "request cancelled"));
      const identity = fingerprint({ root: input.root ?? input.repoRoot, outDir: input.outDir, options: input.options ?? input });
      let state = roots.get(identity.root);
      if (!state) { state = { running: null, queue: [] }; roots.set(identity.root, state); }
      let entry = state.running?.identity.fingerprint === identity.fingerprint ? state.running : state.queue.find((candidate) => candidate.identity.fingerprint === identity.fingerprint);
      if (!entry) {
        entry = { identity, state, waiters: new Set(), work: null, settled: false };
        state.queue.push(entry);
      }
      const waiter = attach(entry, signal);
      startNext(state);
      return waiter;
    },
    waitForIdle() {
      if (![...roots.values()].some((state) => state.running || state.queue.length > 0)) return Promise.resolve();
      return new Promise((resolveIdle) => idleWaiters.add(resolveIdle));
    },
  });
}

#[test]
fn maintain_readme_pointer_creates_block_first_time() {
    let dir = tempdir("readme-create");
    fs::write(dir.join("README.md"), "# My Project\n\nSome content.\n").unwrap();
    let mode = maintain_readme_pointer(&dir).unwrap();
    assert_eq!(mode, ReadmePointerMode::Created);
    let text = fs::read_to_string(dir.join("README.md")).unwrap();
    assert!(text.contains("<!-- blueprint:docs:start -->"));
    assert!(text.contains("<!-- blueprint:docs:end -->"));
    assert!(text.contains("[Product overview](docs/product.md)"));
    let _ = fs::remove_dir_all(&dir);
}

#[test]
fn maintain_readme_pointer_is_idempotent_on_second_call() {
    let dir = tempdir("readme-idempotent");
    fs::write(dir.join("README.md"), "# My Project\n").unwrap();
    maintain_readme_pointer(&dir).unwrap();
    let first = fs::read_to_string(dir.join("README.md")).unwrap();
    let mode = maintain_readme_pointer(&dir).unwrap();
    assert_eq!(mode, ReadmePointerMode::Updated);
    let second = fs::read_to_string(dir.join("README.md")).unwrap();
    assert_eq!(first, second, "second run must not perturb an already-correct block");
    let _ = fs::remove_dir_all(&dir);
}

#[test]
fn maintain_readme_pointer_updates_stale_block_content() {
    let dir = tempdir("readme-update");
    let stale = "# Proj\n<!-- blueprint:docs:start -->\nOLD CONTENT\n<!-- blueprint:docs:end -->\nTail text\n";
    fs::write(dir.join("README.md"), stale).unwrap();
    let mode = maintain_readme_pointer(&dir).unwrap();
    assert_eq!(mode, ReadmePointerMode::Updated);
    let text = fs::read_to_string(dir.join("README.md")).unwrap();
    assert!(!text.contains("OLD CONTENT"));
    assert!(text.contains("Tail text"));
    assert!(text.contains("[Architecture](docs/architecture.md)"));
    let _ = fs::remove_dir_all(&dir);
}

#[test]

#[test]
fn generate_docs_writes_fresh_docs_and_readme_pointer() {
    let dir = tempdir("gen-write");
    let agent = dir.join(".agent");
    fs::create_dir_all(&agent).unwrap();
    fs::write(
        agent.join("map.json"),
        r#"{"repo":"demo-repo","stats":{"files":1,"docs":0,"claims":0,"codeRefs":0},"nodes":[]}"#,
    )
    .unwrap();
    fs::write(dir.join("README.md"), "# demo-repo\n").unwrap();

    let result = generate_docs(&dir, GenerateDocsOptions::default()).unwrap();
    assert_eq!(result.mode, "wrote");
    assert_eq!(result.wrote, vec![DOC_PATH_PRODUCT.to_string(), DOC_PATH_ARCHITECTURE.to_string()]);
    assert!(dir.join(DOC_PATH_PRODUCT).exists());
    assert!(dir.join(DOC_PATH_ARCHITECTURE).exists());
    assert_eq!(result.readme, Some(ReadmePointerMode::Created));

    let product_text = fs::read_to_string(dir.join(DOC_PATH_PRODUCT)).unwrap();
    assert!(product_text.starts_with("<!-- generated by blueprint"));
    assert!(product_text.contains("demo-repo — Product Overview"));

    // Re-running with unchanged inputs regenerates the SAME generation id
    // (byte-identical rebuild on an unchanged repo).
    let result2 = generate_docs(&dir, GenerateDocsOptions::default()).unwrap();
    assert_eq!(result2.mode, "wrote");
    let product_text2 = fs::read_to_string(dir.join(DOC_PATH_PRODUCT)).unwrap();
    assert_eq!(product_text, product_text2);

    let _ = fs::remove_dir_all(&dir);
}

#[test]
fn generate_docs_reports_conflict_for_handwritten_target() {
    let dir = tempdir("gen-conflict");
    let agent = dir.join(".agent");
    fs::create_dir_all(&agent).unwrap();
    fs::write(
        agent.join("map.json"),
        r#"{"repo":"demo","stats":{},"nodes":[]}"#,
    )
    .unwrap();
    let docs_dir = dir.join("docs");
    fs::create_dir_all(&docs_dir).unwrap();
    fs::write(docs_dir.join("product.md"), "# Hand-written product doc\n").unwrap();
    fs::write(docs_dir.join("architecture.md"), "# Hand-written arch doc\n").unwrap();

    let result = generate_docs(&dir, GenerateDocsOptions::default()).unwrap();
    assert_eq!(result.mode, "docs_conflict");
    assert_eq!(result.conflicts.len(), 2);
    assert_eq!(result.fallback.len(), 2);
    assert!(dir.join(".agent/docs/product.md").exists());
    assert!(dir.join(".agent/docs/architecture.md").exists());
    // Hand-written targets must be left untouched.
    assert_eq!(
        fs::read_to_string(docs_dir.join("product.md")).unwrap(),
        "# Hand-written product doc\n"
    );

    let _ = fs::remove_dir_all(&dir);
}

#[test]
fn generate_docs_no_readme_link_skips_readme_maintenance() {
    let dir = tempdir("gen-no-readme");
    let agent = dir.join(".agent");
    fs::create_dir_all(&agent).unwrap();
    fs::write(agent.join("map.json"), r#"{"repo":"demo","stats":{},"nodes":[]}"#).unwrap();
    fs::write(dir.join("README.md"), "# demo\n").unwrap();

    let result = generate_docs(&dir, GenerateDocsOptions { no_readme_link: true }).unwrap();
    assert_eq!(result.mode, "wrote");
    assert_eq!(result.readme, None);
    let readme_text = fs::read_to_string(dir.join("README.md")).unwrap();
    assert!(!readme_text.contains("blueprint:docs:start"));

    let _ = fs::remove_dir_all(&dir);
}

#[test]
fn generate_docs_retires_start_here_on_success() {
    let dir = tempdir("gen-retire-start-here");
    let agent = dir.join(".agent");
    fs::create_dir_all(&agent).unwrap();
    fs::write(agent.join("map.json"), r#"{"repo":"demo","stats":{},"nodes":[]}"#).unwrap();
    fs::write(agent.join("START-HERE.md"), "old bootstrap doc").unwrap();

    let result = generate_docs(&dir, GenerateDocsOptions { no_readme_link: true }).unwrap();
    assert_eq!(result.retired, vec![".agent/START-HERE.md".to_string()]);
    assert!(!agent.join("START-HERE.md").exists());

    let _ = fs::remove_dir_all(&dir);
}

/// Minimal claim shape used by [`product_sections`], mirroring the JS
/// claim object's `{ status, text, source, line }` fields.
#[derive(Debug, Clone)]
pub struct DocClaim {
    pub status: String,
    pub text: String,
    pub source: String,
    pub line: Value,
}

fn product_sections(repo: &str, claims: &[DocClaim], map: &Value, generation_id: &str) -> String {
    let header = generation_header(generation_id);
    let eligible: Vec<&DocClaim> = claims
        .iter()
        .filter(|c| {
            matches!(c.status.as_str(), "implemented" | "partial" | "claim") && !c.text.is_empty()
        })
        .collect();

    let mut by_source: Vec<(String, Vec<&DocClaim>)> = Vec::new();
    for c in &eligible {
        if let Some(entry) = by_source.iter_mut().find(|(k, _)| k == &c.source) {
            entry.1.push(c);
        } else {
            by_source.push((c.source.clone(), vec![c]));
        }
    }
    by_source.sort_by(|a, b| a.0.cmp(&b.0));

    let capability_rows: Vec<String> = by_source
        .iter()
        .take(12)
        .map(|(path, list)| {
            let top = list[0];
            format!(
                "- **{}** — {} _(source: {}:{})_",
                path,
                top.text,
                top.source,
                value_to_display(&top.line)
            )
        })
        .collect();

    let canonical = ["AGENTS.md", "CLAUDE.md", "README.md"];
    let surface_rows: Vec<String> = map
        .get("nodes")
        .and_then(Value::as_array)
        .cloned()
        .unwrap_or_default()
        .into_iter()
        .filter(|n| {
            n.get("kind").and_then(Value::as_str) == Some("doc")
                && n.get("path")
                    .and_then(Value::as_str)
                    .map(|p| canonical.contains(&p))
                    .unwrap_or(false)
        })
        .map(|n| {
            let path = n.get("path").and_then(Value::as_str).unwrap_or("");
            format!("- `{}` _(source: {}:1)_", path, path)
        })
        .take(5)
        .collect();

    let mut lines: Vec<String> = vec![
        header,
        String::new(),
        format!("# {} — Product Overview", repo),
        String::new(),
        "Code-grounded description of what this product is and does. Generated from verified doc claims;".to_string(),
        "audience and positioning statements come **only** from existing repository docs, never invented.".to_string(),
        String::new(),
        "## Capabilities".to_string(),
        String::new(),
        "Plain-language features derived from the verified claim inventory. Each row points back to its source.".to_string(),
        String::new(),
    ];
    if capability_rows.is_empty() {
        lines.push("- _No verified capability claims yet._".to_string());
    } else {
        lines.extend(capability_rows);
    }
    lines.push(String::new());
    lines.push("## Entry points".to_string());
    lines.push(String::new());
    lines.push("User-visible surfaces named by the repository docs:".to_string());
    lines.push(String::new());
    if surface_rows.is_empty() {
        lines.push("- _No canonical entry-point docs found._".to_string());
    } else {
        lines.extend(surface_rows);
    }
    lines.push(String::new());
    lines.push("## Honesty / Gaps".to_string());
    lines.push(String::new());
    lines.push("Items the docs claim but no implementation file references — and the reverse — surface here as".to_string());
    lines.push("findings. If a flow is named in user-facing copy but absent from the code graph, it is listed".to_string());
    lines.push("below, not omitted.".to_string());
    lines.push(String::new());
    lines.push("- _See `.agent/stale.json` for the canonical missing-reference list (provenance: .agent/stale.json)._".to_string());
    lines.push(String::new());

    lines.join("\n")
}

fn value_to_display(v: &Value) -> String {
    match v {
        Value::String(s) => s.clone(),
        Value::Null => String::new(),
        other => other.to_string(),
    }
}


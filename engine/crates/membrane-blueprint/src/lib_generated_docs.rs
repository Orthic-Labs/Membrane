fn markdown_cell(value: &str) -> String {
    let escaped = value.replace('|', "\\|");
    let collapsed = collapse_whitespace(&escaped);
    collapsed.trim().to_string()
}

fn collapse_whitespace(s: &str) -> String {
    let mut out = String::with_capacity(s.len());
    let mut last_was_space = false;
    for c in s.chars() {
        if c.is_whitespace() {
            if !last_was_space {
                out.push(' ');
            }
            last_was_space = true;
        } else {
            out.push(c);
            last_was_space = false;
        }
    }
    out
}

fn workflow_step_text(step: &Value) -> String {
    match step {
        Value::String(s) => s.clone(),
        Value::Object(_) => ["name", "component", "label", "step", "id"]
            .iter()
            .find_map(|k| step.get(*k).and_then(Value::as_str))
            .unwrap_or("")
            .to_string(),
        _ => String::new(),
    }
}

fn workflow_steps(flow: &Value) -> Vec<String> {
    match flow {
        Value::String(s) => split_arrow(s),
        Value::Array(items) => items
            .iter()
            .map(workflow_step_text)
            .map(|s| s.trim().to_string())
            .filter(|s| !s.is_empty())
            .collect(),
        Value::Object(_) => {
            let structured = flow
                .get("steps")
                .or_else(|| flow.get("path"))
                .or_else(|| flow.get("components"));
            if let Some(Value::Array(items)) = structured {
                return items
                    .iter()
                    .map(workflow_step_text)
                    .map(|s| s.trim().to_string())
                    .filter(|s| !s.is_empty())
                    .collect();
            }
            let text = flow
                .get("flow")
                .or_else(|| flow.get("dataFlow"))
                .or_else(|| flow.get("description"));
            match text {
                Some(Value::String(s)) => workflow_steps(&json!(s)),
                _ => Vec::new(),
            }
        }
        _ => Vec::new(),
    }
}

fn split_arrow(s: &str) -> Vec<String> {
    // Mirrors `flow.split(/\s*(?:->|→)\s*/)`.
    let mut parts = Vec::new();
    let mut current = String::new();
    let chars: Vec<char> = s.chars().collect();
    let mut i = 0;
    while i < chars.len() {
        if chars[i] == '-' && chars.get(i + 1) == Some(&'>') {
            parts.push(current.trim().to_string());
            current = String::new();
            i += 2;
        } else if chars[i] == '→' {
            parts.push(current.trim().to_string());
            current = String::new();
            i += 1;
        } else {
            current.push(chars[i]);
            i += 1;
        }
    }
    parts.push(current.trim().to_string());
    parts.into_iter().filter(|s| !s.is_empty()).collect()
}

fn compact_workflow_label(value: &str) -> String {
    let no_backticks = value.replace('`', "");
    let mut label = collapse_whitespace(&no_backticks).trim().to_string();
    if let Some(colon) = label.find(':') {
        if colon > 0 && colon <= 48 && !label[..colon].contains("::") {
            label = label[..colon].to_string();
        }
    }
    label = label.trim_end_matches(|c: char| c == '.' || c == ';' || c == ',' || c.is_whitespace()).to_string();
    // Re-apply the exact JS semantics: only trailing [.;,]\s* is stripped,
    // not arbitrary trailing whitespace beyond that punctuation run. The
    // trim_end_matches above over-strips plain trailing whitespace too,
    // which is harmless here since collapse_whitespace already trimmed.
    let chars: Vec<char> = label.chars().collect();
    if chars.len() > 88 {
        let truncated: String = chars[..85].iter().collect();
        label = format!("{}…", truncated.trim_end());
    }
    label.replace('\\', "/").replace('"', "'").replace('\n', " ")
}

fn component_workflow_mermaid(architecture: &Value) -> Option<String> {
    let data_flow = architecture.get("dataFlow").and_then(Value::as_array).cloned().unwrap_or_default();
    let chains: Vec<Vec<String>> = data_flow
        .iter()
        .map(workflow_steps)
        .map(|steps| {
            steps
                .iter()
                .map(|s| compact_workflow_label(s))
                .filter(|s| !s.is_empty())
                .collect::<Vec<String>>()
        })
        .filter(|steps: &Vec<String>| steps.len() >= 2)
        .collect();
    if chains.is_empty() {
        return None;
    }

    let mut ids: Vec<(String, String)> = Vec::new();
    let mut edges: Vec<String> = Vec::new();
    let id_of = |ids: &[(String, String)], label: &str| -> Option<String> {
        ids.iter().find(|(l, _)| l == label).map(|(_, id)| id.clone())
    };
    for chain in &chains {
        for label in chain {
            if id_of(&ids, label).is_none() {
                let id = format!("c{}", ids.len());
                ids.push((label.clone(), id));
            }
        }
        for pair in chain.windows(2) {
            let a = id_of(&ids, &pair[0]).unwrap();
            let b = id_of(&ids, &pair[1]).unwrap();
            let edge = format!("{} --> {}", a, b);
            if !edges.contains(&edge) {
                edges.push(edge);
            }
        }
    }

    let mut lines = vec![
        "flowchart LR".to_string(),
        "  %% component workflow from .agent/understanding.json".to_string(),
    ];
    lines.extend(ids.iter().map(|(label, id)| format!("  {}[\"{}\"]", id, label)));
    lines.extend(edges.iter().map(|edge| format!("  {}", edge)));
    Some(lines.join("\n"))
}

fn architecture_sections(repo: &str, _map: &Value, stale: &Value, understanding: &Value, generation_id: &str) -> String {
    let header = generation_header(generation_id);
    let default_arch = json!({});
    let architecture = understanding.get("architecture").unwrap_or(&default_arch);

    let component_rows: Vec<String> = architecture
        .get("components")
        .and_then(Value::as_array)
        .cloned()
        .unwrap_or_default()
        .iter()
        .map(|component| {
            let name = markdown_cell(
                component
                    .get("name")
                    .or_else(|| component.get("component"))
                    .and_then(Value::as_str)
                    .unwrap_or("Unnamed component"),
            );
            let note = markdown_cell(
                component
                    .get("note")
                    .or_else(|| component.get("role"))
                    .and_then(Value::as_str)
                    .unwrap_or(""),
            );
            let evidence = markdown_cell(
                component
                    .get("evidence")
                    .and_then(Value::as_str)
                    .unwrap_or("Undetermined — no evidence recorded"),
            );
            if note.is_empty() {
                format!("- **{}** _(source: {})_", name, evidence)
            } else {
                format!("- **{}** — {} _(source: {})_", name, note, evidence)
            }
        })
        .collect();

    let workflow = component_workflow_mermaid(architecture);
    let missing_count = stale.get("missingReferences").and_then(Value::as_array).map(|a| a.len()).unwrap_or(0);
    let stale_claims_count = stale.get("staleClaims").and_then(Value::as_array).map(|a| a.len()).unwrap_or(0);

    let classified_flows = architecture.get("flows").and_then(Value::as_array).cloned().unwrap_or_default();
    let mut flow_rows: Vec<String> = Vec::new();
    if classified_flows.is_empty() {
        flow_rows.push("_No classified product flows yet; run Blueprint Phase 2 synthesis._".to_string());
    } else {
        flow_rows.push("| Flow | Status | Evidence | Impact |".to_string());
        flow_rows.push("|---|---|---|---|".to_string());
        for flow in &classified_flows {
            let name = markdown_cell(flow.get("name").or_else(|| flow.get("flow")).and_then(Value::as_str).unwrap_or("Unnamed flow"));
            let status = markdown_cell(flow.get("status").and_then(Value::as_str).unwrap_or("undetermined"));
            let evidence = markdown_cell(flow.get("evidence").and_then(Value::as_str).unwrap_or("Undetermined"));
            let impact = markdown_cell(flow.get("impact").and_then(Value::as_str).unwrap_or(""));
            flow_rows.push(format!("| {} | {} | {} | {} |", name, status, evidence, impact));
        }
    }

    let synthesized_coverage = architecture.get("capabilityCoverage").and_then(Value::as_array).cloned().unwrap_or_default();
    let mut capability_rows: Vec<String> = Vec::new();
    if synthesized_coverage.is_empty() {
        capability_rows.push("| Capability | Status | Evidence |".to_string());
        capability_rows.push("|---|---|---|".to_string());
        capability_rows.push("| document/ADR/plan claims | covered | _source: .agent/map.json:claims_ |".to_string());
        capability_rows.push("| code symbols and relationships | partial until Phase 2 classifies provider coverage | _source: .agent/graph/graph.db_ |".to_string());
        capability_rows.push("| contradiction/staleness arbitration | covered | _source: .agent/stale.json_ |".to_string());
    } else {
        capability_rows.push("| Capability | Status | Evidence | Provider |".to_string());
        capability_rows.push("|---|---|---|---|".to_string());
        for row in &synthesized_coverage {
            let capability = markdown_cell(row.get("capability").or_else(|| row.get("name")).and_then(Value::as_str).unwrap_or("Unnamed capability"));
            let status = markdown_cell(row.get("status").and_then(Value::as_str).unwrap_or("undetermined"));
            let evidence = markdown_cell(row.get("evidence").and_then(Value::as_str).unwrap_or("Undetermined"));
            let provider = markdown_cell(row.get("provider").and_then(Value::as_str).unwrap_or(""));
            capability_rows.push(format!("| {} | {} | {} | {} |", capability, status, evidence, provider));
        }
    }

    let mut lines: Vec<String> = vec![
        header,
        String::new(),
        format!("# {} — Architecture", repo),
        String::new(),
        "Technical overview of components, interfaces, classified flow inventory, and capability coverage.".to_string(),
        "The deterministic Phase-1 graph supplies the evidence substrate; Phase-2 understanding supplies".to_string(),
        "the human component names and operational flow. Raw file and symbol nodes are intentionally omitted.".to_string(),
        String::new(),
    ];
    if let Some(summary) = architecture.get("summary").and_then(Value::as_str) {
        if !summary.is_empty() {
            lines.push(markdown_cell(summary));
            lines.push(String::new());
        }
    }
    lines.push("## System workflow".to_string());
    lines.push(String::new());
    if let Some(w) = &workflow {
        lines.push("```mermaid".to_string());
        lines.push(w.clone());
        lines.push("```".to_string());
        lines.push(String::new());
        lines.push("_(source: .agent/understanding.json:architecture.dataFlow)_".to_string());
    } else {
        lines.push("_No synthesized component workflow yet; run Blueprint Phase 2 synthesis._".to_string());
    }
    lines.push(String::new());
    lines.push("## Components".to_string());
    lines.push(String::new());
    if component_rows.is_empty() {
        lines.push("- _No synthesized components yet; run Blueprint Phase 2 synthesis._".to_string());
    } else {
        lines.extend(component_rows);
    }
    lines.push(String::new());
    lines.push("## Flow inventory".to_string());
    lines.push(String::new());
    lines.extend(flow_rows);
    lines.push(String::new());
    lines.push("## Capability coverage".to_string());
    lines.push(String::new());
    lines.extend(capability_rows);
    lines.push(String::new());
    lines.push("## Health & Security (loud-partial when graph is missing)".to_string());
    lines.push(String::new());
    lines.push(format!("- Stale claims: **{}** _(source: .agent/stale.json:staleClaims)_", stale_claims_count));
    lines.push(format!("- Missing references: **{}** _(source: .agent/stale.json:missingReferences)_", missing_count));
    lines.push("- Detailed health and security findings live in `.agent/understanding.json`; every synthesized".to_string());
    lines.push("  component and flow above retains its recorded evidence. _(source: .agent/understanding.json)_".to_string());
    lines.push(String::new());
    lines.push("## Status".to_string());
    lines.push(String::new());
    lines.push(format!("Generated from index signature `{}`. Unchanged-repo rebuilds are byte-identical.", generation_id));
    lines.push(String::new());

    lines.join("\n")
}


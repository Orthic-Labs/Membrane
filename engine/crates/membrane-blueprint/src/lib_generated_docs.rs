#[derive(Debug, Clone, PartialEq, Eq)]
pub enum ReadmePointerMode {
    Absent,
    Created,
    Updated,
}

/// Mirrors `maintainReadmePointer`.
pub fn maintain_readme_pointer(root: &Path) -> std::io::Result<ReadmePointerMode> {
    let readme_path = root.join("README.md");
    let text = match fs::read_to_string(&readme_path) {
        Ok(t) => t,
        Err(_) => return Ok(ReadmePointerMode::Absent),
    };
    let block = [
        MARKER,
        "## Repository truth docs",
        "- [Product overview](docs/product.md) — what this is and does (generated, code-grounded)",
        "- [Architecture](docs/architecture.md) — components, flows, interfaces (generated, code-grounded)",
        END_MARKER,
    ]
    .join("\n");

    let start_idx = text.find(MARKER);
    let end_idx = start_idx.and_then(|s| text[s..].find(END_MARKER).map(|i| s + i));

    if start_idx.is_none() || end_idx.is_none() {
        let next = if text.ends_with('\n') {
            format!("{}\n{}\n", text, block)
        } else {
            format!("{}\n{}\n", text, block)
        };
        write_text(&readme_path, &next)?;
        return Ok(ReadmePointerMode::Created);
    }

    let start_idx = start_idx.unwrap();
    let end_idx = end_idx.unwrap();
    let before = &text[..start_idx];
    let after_raw = &text[end_idx + END_MARKER.len()..];
    let after = if after_raw.trim().is_empty() {
        "\n".to_string()
    } else if after_raw.starts_with('\n') || after_raw.starts_with("\r\n") {
        after_raw.to_string()
    } else {
        format!("\n{}", after_raw)
    };
    let next = format!("{}{}{}", before, block, after);
    if next != text {
        write_text(&readme_path, &next)?;
    }
    Ok(ReadmePointerMode::Updated)
}


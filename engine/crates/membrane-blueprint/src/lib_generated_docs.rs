//! Native Rust port of `blueprint/src/lib/generated-docs.mjs`.
//!
//! Lane LIB4 (r5 closure): this module has no prior native equivalent.
//! Blueprint B6.5 generated human docs — regenerates `docs/product.md` and
//! `docs/architecture.md` with a generation header (no timestamp,
//! byte-identical on an unchanged repo), per-section provenance, clobber
//! safety (typed `docs_conflict` when a hand-written file lacks the
//! generation marker, falling back to `.agent/docs/`), an optional README
//! pointer block, and `START-HERE.md` retirement on every successful
//! build.
//!
//! `hash-wasm`'s XXH3-128 becomes `xxhash_rust::xxh3::xxh3_128` (already a
//! crate dependency, used the same way elsewhere in this crate, e.g.
//! `identity.rs`). `openStoreReadOnly`/`closeStore` from
//! `../graph/store-sqlite.mjs` become a direct read-only `rusqlite`
//! connection opened by this module itself (mirroring the legacy module's
//! own independent read-only handle, not a call into `store.rs`, which
//! lane rules forbid touching).

use rusqlite::{Connection, OpenFlags};
use serde_json::{json, Value};
use std::fs;
use std::path::Path;
use xxhash_rust::xxh3::xxh3_128;

pub const VERSION: &str = "0.2.0";
const GENERATION_HEADER_PREFIX: &str = "<!-- generated by blueprint";
const MARKER: &str = "<!-- blueprint:docs:start -->";
const END_MARKER: &str = "<!-- blueprint:docs:end -->";
pub const DOC_PATH_PRODUCT: &str = "docs/product.md";
pub const DOC_PATH_ARCHITECTURE: &str = "docs/architecture.md";
const FALLBACK_DIR: &str = ".agent/docs";
const START_HERE_PATH: &str = ".agent/START-HERE.md";

fn id_exclude(path: &str) -> bool {
    path == "README.md" || path == DOC_PATH_PRODUCT || path == DOC_PATH_ARCHITECTURE
}

/// Read the graph manifest from the store's SQLite database directly
/// (read-only), mirroring `readStoredManifest`. Returns `None` when no
/// graph has been built or the read fails for any reason (matching the
/// JS try/catch-to-null fallback).
pub fn read_stored_manifest(root: &Path) -> Option<Value> {
    let db_path = root.join(".agent").join("graph").join("graph.db");
    if !db_path.exists() {
        return None;
    }
    let conn = Connection::open_with_flags(&db_path, OpenFlags::SQLITE_OPEN_READ_ONLY).ok()?;
    let mut stmt = conn
        .prepare("SELECT value FROM generation WHERE key = 'manifest'")
        .ok()?;
    let value: Option<String> = stmt
        .query_row([], |row| row.get(0))
        .ok();
    value.and_then(|v| serde_json::from_str(&v).ok())
}

fn xxh3_hex(input: &str) -> String {
    format!("{:032x}", xxh3_128(input.as_bytes()))
}

/// Stats subset used by [`generated_docs_generation_id`], mirroring
/// `stats?.files` / `stats?.docs` / `stats?.claims` / `stats?.codeRefs`.
#[derive(Debug, Clone, Copy, Default)]
pub struct DocsStats {
    pub files: i64,
    pub docs: i64,
    pub claims: i64,
    pub code_refs: i64,
}

/// Stable identifier for the source set. Mirrors
/// `generatedDocsGenerationId`. `files` are plain path strings (the JS
/// accepts `entry.path ?? entry`; callers here pass the resolved path
/// directly).
pub fn generated_docs_generation_id(
    files: &[String],
    stats: &DocsStats,
    source_signature: &str,
) -> String {
    let mut sorted_paths: Vec<&str> = files
        .iter()
        .map(|s| s.as_str())
        .filter(|p| !p.is_empty() && !id_exclude(p))
        .collect();
    sorted_paths.sort();
    let joined_paths = sorted_paths.join("\n");
    let input = [
        source_signature,
        &joined_paths,
        &stats.files.to_string(),
        &stats.docs.to_string(),
        &stats.claims.to_string(),
        &stats.code_refs.to_string(),
    ]
    .join("\n");
    xxh3_hex(&input)
}

/// Mirrors `generationHeader`.
pub fn generation_header(generation_id: &str) -> String {
    format!(
        "{} {} gen:{} — edit code/docs sources, not this file -->",
        GENERATION_HEADER_PREFIX, VERSION, generation_id
    )
}

/// Mirrors `isGenerated`: a missing file counts as generated (safe to
/// overwrite); an existing file is generated only if its first line
/// carries the generation-header prefix.
pub fn is_generated(target_path: &Path) -> bool {
    let text = match fs::read_to_string(target_path) {
        Ok(t) => t,
        Err(_) => return true,
    };
    let first_line = text.split(['\n']).next().unwrap_or("");
    let first_line = first_line.strip_suffix('\r').unwrap_or(first_line);
    first_line.starts_with(GENERATION_HEADER_PREFIX)
}

fn write_text(path: &Path, body: &str) -> std::io::Result<()> {
    if let Some(parent) = path.parent() {
        fs::create_dir_all(parent)?;
    }
    let out = if body.ends_with('\n') {
        body.to_string()
    } else {
        format!("{}\n", body)
    };
    fs::write(path, out)
}


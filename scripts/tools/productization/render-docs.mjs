/**
 * Extract local markdown link targets from README text. Returns relative paths
 * only — external URLs, anchors, and mailto links are not filesystem targets.
 */
export function extractLocalLinks(markdownText) {
  const targets = [];
  const pattern = /\[[^\]]*\]\(([^)\s]+)(?:\s+"[^"]*")?\)/g;
  let match;
  while ((match = pattern.exec(markdownText)) !== null) {
    const target = match[1];
    if (/^(https?:|mailto:|#)/.test(target)) continue;
    targets.push(target.split("#")[0]);
  }
  return [...new Set(targets)].sort();
}

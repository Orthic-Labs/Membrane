function platformSentence(platforms) {
  const tier1 = platforms.tier1.join(" and ");
  const bestEffort = platforms.bestEffort.length
    ? ` ${platforms.bestEffort.join(" and ")} is tier-2 best-effort.`
    : "";
  if (platforms.tier1.length === 1 && platforms.tier1[0] === "Windows" && !platforms.bestEffort.length) {
    return "The sole supported current target is **Windows** (tier 1). Other targets are not current supported targets.";
  }
  return `Supported platforms are **${tier1}** (tier 1).${bestEffort}`;
}

